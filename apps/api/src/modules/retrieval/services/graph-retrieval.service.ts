/**
 * MindVault — Retrieval Engine: Graph Retrieval Channel Service
 *
 * Implements Channel 3 (Knowledge Graph Evidence Retrieval) of the GraphRAG pipeline:
 * 1. N-Gram Generation & Lexical Normalization
 * 2. Stage 1 — Seed Entity Discovery (lexical canonical, alias, and shared-vector semantic)
 * 3. Stage 2 — Bounded Graph Evidence Expansion (2-hop recursive traversal)
 * 4. Workspace-Safe In-Memory Candidate Filtering
 * 5. Fine-Grained Timing Telemetry
 *
 * Mandatory Invariants:
 * - NEVER generates query embeddings internally (reuses passed queryVector).
 * - Enforces workspace isolation at all stages.
 * - Gracefully returns empty results when 0 seeds or evidence chunks match.
 */

import type {
  RawGraphChunkRow,
  RawGraphRelationRow,
  DiscoveredSeedEntity,
  RetrievalFilters,
} from '@mindvault/shared';
import { graphRepository } from '../../graph/repositories/graph.repository.js';
import type { IGraphRepository } from '../../graph/repositories/graph.repository.interface.js';
import { EntityNormalizer } from '../../graph/normalizers/entity.normalizer.js';

export interface GraphRetrievalOptions {
  /** Maximum number of graph evidence chunks to retrieve (default: 20, clamped [1, 50]) */
  topK?: number;
  /** Shared 768-dimensional query vector generated by RetrievalService (optional) */
  queryVector?: number[];
  /** Pre-extracted terms from QueryProcessor (optional) */
  terms?: string[];
  /** Pre-extracted quoted phrases from QueryProcessor (optional) */
  exactPhrases?: string[];
  /** Workspace retrieval filters for post-query candidate refinement */
  filters?: RetrievalFilters;
  /** Minimum relationship confidence threshold (default: 0.6) */
  minConfidence?: number;
  /** Minimum relationship weight threshold (default: 0.5) */
  minWeight?: number;
  /** Conversational focus entity hints to prioritize in seed discovery (Phase 6.7) */
  focusEntityHints?: string[];
}

export interface GraphRetrievalOutput {
  chunks: RawGraphChunkRow[];
  relations: RawGraphRelationRow[];
  seeds: DiscoveredSeedEntity[];
  timings: {
    seedDiscoveryMs: number;
    evidenceTraversalMs: number;
    totalGraphMs: number;
  };
}

export class GraphRetrievalService {
  private static readonly MAX_NGRAMS = 25;
  private static readonly MAX_SEEDS = 5;

  constructor(private readonly graphRepo: IGraphRepository = graphRepository) {}

  /**
   * Extracts and normalizes candidate entity n-grams from query terms, exact phrases, and full query.
   * Produces bounded, deduplicated search terms for seed discovery.
   */
  public static extractNgrams(
    query: string,
    terms?: string[],
    exactPhrases?: string[],
    focusEntityHints?: string[],
  ): string[] {
    const rawGrams = new Set<string>();

    // 0. Focus entity hints from conversational context (highest-priority exact seeds)
    if (focusEntityHints && Array.isArray(focusEntityHints)) {
      for (const hint of focusEntityHints) {
        if (typeof hint === 'string' && hint.trim().length > 0) {
          rawGrams.add(hint.trim());
        }
      }
    }

    // 1. Quoted exact phrases (high-priority multi-word entities)
    if (exactPhrases && Array.isArray(exactPhrases)) {
      for (const phrase of exactPhrases) {
        if (typeof phrase === 'string' && phrase.trim().length > 0) {
          rawGrams.add(phrase.trim());
        }
      }
    }

    // 2. Full query string (handles direct entity lookups like "PostgreSQL WAL")
    if (query && typeof query === 'string' && query.trim().length > 0) {
      rawGrams.add(query.trim());
    }

    // 3. Pre-extracted terms or whitespace tokenization
    const tokens: string[] =
      terms && Array.isArray(terms) && terms.length > 0
        ? terms.filter((t) => typeof t === 'string' && t.trim().length > 0)
        : query
            .replace(/[^\p{L}\p{N}\s+#./\-_]/gu, ' ')
            .split(/\s+/)
            .filter((t) => t.length > 0);

    // 4. Generate 1-grams, 2-grams, and 3-grams
    const numTokens = tokens.length;
    for (let i = 0; i < numTokens; i++) {
      // 1-gram
      rawGrams.add(tokens[i]);

      // 2-gram
      if (i + 1 < numTokens) {
        rawGrams.add(`${tokens[i]} ${tokens[i + 1]}`);
      }

      // 3-gram
      if (i + 2 < numTokens) {
        rawGrams.add(`${tokens[i]} ${tokens[i + 1]} ${tokens[i + 2]}`);
      }
    }

    // 5. Normalize through EntityNormalizer, filter noise, and deduplicate
    const normalizedSet = new Set<string>();
    for (const raw of rawGrams) {
      const normalized = EntityNormalizer.normalize(raw);
      // Retain terms with at least 2 characters (or valid single character technical terms if applicable)
      if (normalized.length >= 2) {
        normalizedSet.add(normalized);
      }
    }

    // 6. Return bounded list
    return Array.from(normalizedSet).slice(0, this.MAX_NGRAMS);
  }

  /**
   * Retrieves graph evidence chunks and supporting relations for a query within a workspace.
   */
  public async retrieveChunks(
    workspaceId: string,
    query: string,
    options?: GraphRetrievalOptions,
  ): Promise<GraphRetrievalOutput> {
    const totalStart = performance.now();
    const timings = {
      seedDiscoveryMs: 0,
      evidenceTraversalMs: 0,
      totalGraphMs: 0,
    };

    // 1. Generate normalized candidate entity n-grams
    const ngrams = GraphRetrievalService.extractNgrams(
      query,
      options?.terms,
      options?.exactPhrases,
      options?.focusEntityHints,
    );

    // 2. Stage 1: Seed Entity Discovery
    const seedStart = performance.now();
    const seeds = await this.graphRepo.discoverEntitySeeds({
      workspaceId,
      ngrams,
      queryVector: options?.queryVector,
      maxSeeds: GraphRetrievalService.MAX_SEEDS,
    });
    timings.seedDiscoveryMs = Math.round((performance.now() - seedStart) * 100) / 100;

    // Early exit if no seeds discovered (clean empty result, not an error)
    if (!seeds || seeds.length === 0) {
      timings.totalGraphMs = Math.round((performance.now() - totalStart) * 100) / 100;
      return {
        chunks: [],
        relations: [],
        seeds: [],
        timings,
      };
    }

    // 3. Stage 2: Bounded Graph Evidence Expansion
    const evidenceStart = performance.now();
    const seedEntityIds = seeds.map((s) => s.entityId);
    const topK = Math.min(Math.max(options?.topK ?? 20, 1), 50);

    const evidenceResult = await this.graphRepo.searchGraphEvidence({
      workspaceId,
      seedEntityIds,
      topK,
      minConfidence: options?.minConfidence ?? 0.6,
      minWeight: options?.minWeight ?? 0.5,
    });
    timings.evidenceTraversalMs = Math.round((performance.now() - evidenceStart) * 100) / 100;

    let filteredChunks = evidenceResult.chunks || [];

    // 4. Workspace-Safe In-Memory Candidate Filtering
    if (options?.filters && filteredChunks.length > 0) {
      const { documentIds, fileTypes, pageStart, pageEnd } = options.filters;

      // Filter by documentIds
      if (documentIds && Array.isArray(documentIds) && documentIds.length > 0) {
        const allowedDocIds = new Set(documentIds);
        filteredChunks = filteredChunks.filter((c) => allowedDocIds.has(c.documentId));
      }

      // Filter by fileTypes (extension)
      if (fileTypes && Array.isArray(fileTypes) && fileTypes.length > 0) {
        const allowedExtensions = new Set(
          fileTypes.map((ft) => ft.toLowerCase().replace(/^\./, '').trim()),
        );
        filteredChunks = filteredChunks.filter((c) =>
          allowedExtensions.has(c.docExtension.toLowerCase().replace(/^\./, '').trim()),
        );
      }

      // Filter by page ranges
      if (pageStart !== undefined && pageStart !== null) {
        filteredChunks = filteredChunks.filter(
          (c) => c.pageEnd === null || c.pageEnd === undefined || c.pageEnd >= pageStart,
        );
      }

      if (pageEnd !== undefined && pageEnd !== null) {
        filteredChunks = filteredChunks.filter(
          (c) => c.pageStart === null || c.pageStart === undefined || c.pageStart <= pageEnd,
        );
      }
    }

    timings.totalGraphMs = Math.round((performance.now() - totalStart) * 100) / 100;

    return {
      chunks: filteredChunks,
      relations: evidenceResult.relations || [],
      seeds,
      timings,
    };
  }

  /**
   * Static convenience facade delegating to the default singleton instance.
   */
  public static async retrieveChunks(
    workspaceId: string,
    query: string,
    options?: GraphRetrievalOptions,
  ): Promise<GraphRetrievalOutput> {
    return graphRetrievalService.retrieveChunks(workspaceId, query, options);
  }
}

export const graphRetrievalService = new GraphRetrievalService();
